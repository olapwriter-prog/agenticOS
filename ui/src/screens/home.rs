//! Home: the agent first. A greeting, the question box, what needs you, quick actions, the
//! conversation, and what happened today.
use crate::State;
use crate::icons;
use crate::theme::*;
use rune::{El, Tx, col, el, icon, row, text_input};
use serde_json::{Value, json};

fn greeting(time: &str) -> &'static str {
    let hour: u32 = time
        .split(':')
        .next()
        .and_then(|h| h.parse().ok())
        .unwrap_or(12);
    match hour {
        5..=11 => "Good morning",
        12..=16 => "Good afternoon",
        17..=21 => "Good evening",
        _ => "Hello",
    }
}

pub fn view(s: &State, st: &Value) -> El {
    let pending = st["pending"].as_array().cloned().unwrap_or_default();
    let owner = st["owner"].as_str().unwrap_or("").to_string();
    let time = st["device"]["time"].as_str().unwrap_or("12:00").to_string();
    let stage = str_of(&st["stage"]);
    let mut page = col().key("cards").w_full().gap(22.0);

    // the greeting, and how the agent is
    let hello = if owner.is_empty() {
        greeting(&time).to_string()
    } else {
        format!("{}, {owner}", greeting(&time))
    };
    let mood = if !pending.is_empty() {
        format!(
            "{} {} you",
            pending.len(),
            if pending.len() == 1 {
                "thing needs"
            } else {
                "things need"
            }
        )
    } else {
        "All quiet. Ask me anything.".to_string()
    };
    let stage_chip = row()
        .key("stage")
        .h(26.0)
        .px(10.0)
        .gap(6.0)
        .center_y()
        .radius(13.0)
        .fill(SURFACE2)
        .child(
            el().size(7.0, 7.0)
                .radius(3.5)
                .fill(if stage == "Active" { GOOD } else { DIM }),
        )
        .child(t(
            if stage.is_empty() {
                "…".to_string()
            } else {
                stage
            },
            CAPTION,
            MUTED,
        ));
    page = page.child(
        col()
            .w_full()
            .gap(6.0)
            .pt(8.0)
            .child(
                row()
                    .w_full()
                    .center_y()
                    .child(t(hello, TITLE, TEXT).grow(1.0).truncate())
                    .child(stage_chip),
            )
            .child(t(mood, BODY, MUTED).key("title-home")),
    );

    // the one thing that matters now, as a field in its signal colour
    page = page.child(priority(st, &pending));

    // the question box
    page = page.child(ask(s));

    // quick actions
    let mut quick = row().key("quick").w_full().gap(10.0);
    for (k, ic, label, say, c) in [
        (
            "quick-camera",
            &icons::CAMERA,
            "Camera",
            "take a photo",
            ACCENT,
        ),
        ("quick-photos", &icons::APPS, "Photos", "photos", ACCENT2),
        ("quick-torch", &icons::BOLT, "Torch", "torch on", WARN),
        ("quick-wifi", &icons::WIFI, "Wi-Fi", "scan wifi", GOOD),
    ] {
        quick = quick.child(quick_tile(k, ic, label, c).on_press(move |s: &mut State| s.ask(say)));
    }
    page = page.child(quick);

    // the screens that do not need the bar: the phone, files, the store
    let mut go = row().key("go").w_full().gap(10.0);
    for (k, ic, label, c, tab) in [
        ("go-phone", &icons::PHONE, "Phone", MINT, crate::Tab::Phone),
        ("go-files", &icons::FOLDER, "Files", LIME, crate::Tab::Files),
        ("go-store", &icons::BAG, "Store", VIOLET, crate::Tab::Store),
    ] {
        go = go.child(quick_tile(k, ic, label, c).on_press(move |s: &mut State| s.tab = tab));
    }
    page = page.child(go);
    // the day, and the lab where the phone learns
    let mut more = row().key("go-more").w_full().gap(10.0);
    for (k, ic, label, c, tab) in [
        ("go-today", &icons::STEPS, "Today", SKY, crate::Tab::Today),
        (
            "go-lab",
            &icons::CHIP,
            "Learning lab",
            VIOLET,
            crate::Tab::Lab,
        ),
    ] {
        more = more.child(quick_tile(k, ic, label, c).on_press(move |s: &mut State| s.tab = tab));
    }
    page = page.child(more);

    // what needs the human
    if !pending.is_empty() {
        let mut list = col()
            .key("waiting")
            .w_full()
            .gap(12.0)
            .child(section("Needs you"));
        for p in &pending {
            list = list.child(approval_card(p));
        }
        page = page.child(list);
    }

    // the dashboard, generated by the backend from what the phone knows now
    if st["dashboard"]["cards"]
        .as_array()
        .is_some_and(|c| !c.is_empty())
    {
        page = page.child(
            col()
                .w_full()
                .gap(10.0)
                .child(section("Today at a glance"))
                .child(crate::genui::dashboard(&st["dashboard"], s)),
        );
    }

    // the conversation, one tap away
    if let Some((q, a)) = s.log.last() {
        let reply = a
            .strip_prefix("done: ")
            .or_else(|| a.strip_prefix("not done: "))
            .unwrap_or(a)
            .to_string();
        page = page.child(
            row()
                .key("open-chat")
                .w_full()
                .padding(14.0)
                .gap(12.0)
                .center_y()
                .radius(22.0)
                .fill(SURFACE)
                .border(1.0, ACCENT.alpha(0.3))
                .role("button")
                .label("Open the conversation")
                .press_scale(0.98)
                .child(tile(&icons::SPARK, ACCENT, 40.0))
                .child(
                    col()
                        .grow(1.0)
                        .shrink()
                        .min_w(0.0)
                        .gap(2.0)
                        .child(t(q.clone(), HEADLINE, TEXT).truncate())
                        .child(
                            t(
                                if reply.is_empty() {
                                    "Thinking…".to_string()
                                } else {
                                    reply
                                },
                                CAPTION,
                                MUTED,
                            )
                            .truncate(),
                        ),
                )
                .child(icon(&icons::NEXT, 18.0).color(DIM))
                .on_press(|s: &mut State| s.chat_open = true),
        );
    }

    // today
    let recent = st["recent"].as_array().cloned().unwrap_or_default();
    let mut today = col()
        .key("recent")
        .w_full()
        .gap(10.0)
        .child(section("Today"));
    let mut box_ = card("recent-card").gap(0.0).py(6.0);
    if recent.is_empty() {
        box_ = box_
            .py(16.0)
            .child(t("Nothing yet. What you ask shows here.", BODY, MUTED));
    }
    for (i, e) in recent.iter().enumerate() {
        let tool = str_of(&e["tool"]);
        let (ic, c, title, _) = describe(&tool, &json!({}));
        let ok = e["reward"].as_f64().unwrap_or(0.0);
        let status = if ok > 0.0 {
            GOOD
        } else if ok < 0.0 {
            BAD
        } else {
            DIM
        };
        if i > 0 {
            box_ = box_.child(divider());
        }
        box_ = box_.child(list_row(
            &format!("recent-{i}"),
            tile(ic, c, 36.0),
            &title,
            &str_of(&e["prompt"]),
            Some(el().size(8.0, 8.0).radius(4.0).fill(status)),
        ));
    }
    today = today.child(box_);
    page.child(today)
}

/// The question box: type, then send. It is the main way to use the phone.
fn ask(s: &State) -> El {
    row()
        .key("ask")
        .w_full()
        .h(58.0)
        .pl(16.0)
        .pr(6.0)
        .gap(10.0)
        .center_y()
        .radius(29.0)
        .fill(SURFACE)
        .border(1.0, ACCENT.alpha(0.35))
        .child(icon(&icons::SPARK, 20.0).color(ACCENT))
        .child(
            text_input(&s.chat, BODY)
                .key("chat")
                .single_line()
                .placeholder("Ask anything…", DIM)
                .grow(1.0)
                .h(22.0)
                .on_edit(|s: &mut State| &mut s.chat)
                .on_submit(|s: &mut State, _tx: &mut Tx| {
                    let said = s.chat.text.trim().to_string();
                    s.chat.clear();
                    s.ask(&said);
                }),
        )
        .child(
            round(
                "ask-send",
                &icons::SEND,
                46.0,
                ACCENT_FILL,
                rune::Color::WHITE,
                "Send",
            )
            .on_press(|s: &mut State| {
                let said = s.chat.text.trim().to_string();
                s.chat.clear();
                s.ask(&said);
            }),
        )
}

/// One action that waits: what it is, in words, and Decline or Approve.
fn approval_card(p: &Value) -> El {
    let id = p["id"].as_u64().unwrap_or(0);
    let tool = str_of(&p["tool"]);
    let (ic, c, title, sub) = describe(&tool, &p["args"]);
    col()
        .key(format!("pending-{id}"))
        .w_full()
        .padding(16.0)
        .gap(14.0)
        .radius(22.0)
        .fill(SURFACE)
        .border(1.0, c.alpha(0.35))
        .child(
            row()
                .w_full()
                .gap(14.0)
                .center_y()
                .child(tile(ic, c, 44.0))
                .child(
                    col()
                        .grow(1.0)
                        .shrink()
                        .min_w(0.0)
                        .gap(2.0)
                        .child(t(title, HEADLINE, TEXT).truncate())
                        .child(
                            t(
                                if sub.is_empty() {
                                    "Waits for your approval".into()
                                } else {
                                    sub
                                },
                                CAPTION,
                                MUTED,
                            )
                            .truncate(),
                        ),
                )
                .child(icon(&icons::LOCK, 16.0).color(DIM)),
        )
        .child(
            row()
                .w_full()
                .gap(10.0)
                .child(
                    pill(&format!("decline-{id}"), "Decline", SURFACE2, TEXT)
                        .grow(1.0)
                        .h(44.0)
                        .on_press(move |s: &mut State| s.send(format!("decline {id}"))),
                )
                .child(
                    pill(
                        &format!("approve-{id}"),
                        "Approve",
                        ACCENT_FILL,
                        rune::Color::WHITE,
                    )
                    .grow(1.0)
                    .h(44.0)
                    .on_press(move |s: &mut State| {
                        // with a PIN set, the sheet asks for it first
                        if s.snap["pin_set"].as_bool() == Some(true) {
                            s.sheet = Some(id);
                            s.pin.clear();
                        } else {
                            s.send(format!("press {id}"));
                        }
                    }),
                ),
        )
}

/// The priority field: actions that wait come first (sun), then unread messages from Android
/// apps (coral), else a calm violet card. Tapping it goes where the thing is.
fn priority(st: &Value, pending: &[Value]) -> El {
    let unread = crate::screens::inbox::unread(st);
    let (kind, label, hero, line, go): (&str, &str, String, String, u8) = if !pending.is_empty() {
        let (_, _, title, sub) = describe(&str_of(&pending[0]["tool"]), &pending[0]["args"]);
        let line = if sub.is_empty() {
            title
        } else {
            format!("{title}: {sub}")
        };
        let n = pending.len();
        (
            "sun",
            "Waiting for you",
            format!("{n} {}", if n == 1 { "action" } else { "actions" }),
            line,
            0,
        )
    } else if unread > 0 {
        let last = st["inbox"]
            .as_array()
            .and_then(|a| a.first())
            .cloned()
            .unwrap_or_default();
        let line = format!(
            "{} on {}: {}",
            str_of(&last["sender"]),
            str_of(&last["app"]),
            str_of(&last["text"])
        );
        ("coral", "Messages", format!("{unread} new"), line, 1)
    } else {
        (
            "violet",
            "Today",
            "All quiet".to_string(),
            "Ask me anything, or pick a tile below.".to_string(),
            2,
        )
    };
    let f = signal_field("priority", kind, label, &hero, &line)
        .min_h(170.0)
        .role("button")
        .label(label)
        .press_scale(0.98);
    match go {
        1 => f.on_press(|s: &mut State| s.tab = crate::Tab::Inbox),
        2 => f.on_press(|s: &mut State| s.chat_open = true),
        _ => f,
    }
}
