//! Screens instead of sentences. A tool answers with a small UI document: a title, cards (each a
//! title, a few lines, a badge, buttons), and buttons for the whole screen. A button carries the
//! words to say back ("send invoice INV/2026-27/0003"), so pressing it is the same request as
//! saying it: tiers and the approval key apply unchanged. The document carries its own text
//! form, so a phone without a screen reads or speaks the same answer.
//!
//! Wire form (one JSON object): {"ui": {"title", "subtitle"?, "kind"?, "cards": [...], "actions": [...]}, "text": "..."}
//!
//! A card can also carry data the screen draws instead of only text: a big number (`metric`), a
//! small chart (`chart`), a bar (`progress`) and a picture (`image`). These are generated by the
//! tools themselves, so what the screen shows follows what was asked: the UI is generated in the
//! backend, as data, and every screen renders it the same way.
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
pub struct Button {
    pub label: String,
    /// what pressing it says to the agent
    pub say: String,
}

/// A big number with what it measures: "24°C", "feels like 26°C", "-1.2% today".
#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
pub struct Metric {
    pub value: String,
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub label: String,
    /// a change, shown in green or red by its sign: "+2.1%", "-3°"
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub delta: String,
}

/// A small chart: one series, a label for each value.
#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
pub struct Chart {
    /// "bar" or "line"
    pub kind: String,
    pub labels: Vec<String>,
    pub values: Vec<f64>,
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub unit: String,
}

/// One step of the agent's work: "done", "run", "wait" (for the owner) or "fail".
#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
pub struct Step {
    pub label: String,
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub detail: String,
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub state: String,
}

/// A small grid: column names and rows of text.
#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
pub struct Table {
    pub columns: Vec<String>,
    pub rows: Vec<Vec<String>>,
}

/// One line of a list: tapping it says `say` back to the agent.
#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
pub struct Item {
    pub title: String,
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub subtitle: String,
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub value: String,
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub icon: String,
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub say: String,
}

/// One column of a comparison. `best` marks the choice the answer recommends.
#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
pub struct Choice {
    pub title: String,
    #[serde(skip_serializing_if = "Vec::is_empty", default)]
    pub lines: Vec<String>,
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub value: String,
    #[serde(skip_serializing_if = "std::ops::Not::not", default)]
    pub best: bool,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
pub struct Card {
    pub title: String,
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub subtitle: String,
    #[serde(skip_serializing_if = "Vec::is_empty", default)]
    pub lines: Vec<String>,
    /// a short tag shown on the card: "₹4,720", "due in 3 days", "best"
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub badge: String,
    /// "ok", "warn", "info" or "" (plain)
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub tone: String,
    #[serde(skip_serializing_if = "Vec::is_empty", default)]
    pub actions: Vec<Button>,
    #[serde(skip_serializing_if = "Option::is_none", default)]
    pub metric: Option<Metric>,
    #[serde(skip_serializing_if = "Option::is_none", default)]
    pub chart: Option<Chart>,
    /// 0.0 to 1.0
    #[serde(skip_serializing_if = "Option::is_none", default)]
    pub progress: Option<f32>,
    /// a picture on the phone, by path
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub image: String,
    /// the agent's work, one line per step
    #[serde(skip_serializing_if = "Vec::is_empty", default)]
    pub steps: Vec<Step>,
    #[serde(skip_serializing_if = "Option::is_none", default)]
    pub table: Option<Table>,
    #[serde(skip_serializing_if = "Vec::is_empty", default)]
    pub items: Vec<Item>,
    /// options side by side
    #[serde(skip_serializing_if = "Vec::is_empty", default)]
    pub compare: Vec<Choice>,
    /// where it came from: "SMS", "WhatsApp", "Connector"
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub source: String,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
pub struct Ui {
    pub title: String,
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub subtitle: String,
    /// what kind of answer this is ("weather", "photo", "money"...), for its icon and colour
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub kind: String,
    #[serde(default)]
    pub cards: Vec<Card>,
    #[serde(skip_serializing_if = "Vec::is_empty", default)]
    pub actions: Vec<Button>,
    /// which chat view draws this by default: "poster", "board", "steps", "thread" or "reader"
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub layout: String,
    /// the colour of its field: sky, mint, sun, coral, violet or lime
    #[serde(skip_serializing_if = "String::is_empty", default)]
    pub accent: String,
}

impl Ui {
    pub fn new(title: impl Into<String>) -> Ui {
        Ui {
            title: title.into(),
            ..Default::default()
        }
    }
    pub fn subtitle(mut self, s: impl Into<String>) -> Ui {
        self.subtitle = s.into();
        self
    }
    pub fn kind(mut self, k: &str) -> Ui {
        self.kind = k.to_string();
        self
    }
    pub fn layout(mut self, l: &str) -> Ui {
        self.layout = l.to_string();
        self
    }
    pub fn accent(mut self, a: &str) -> Ui {
        self.accent = a.to_string();
        self
    }
    pub fn card(mut self, c: Card) -> Ui {
        self.cards.push(c);
        self
    }
    pub fn action(mut self, label: impl Into<String>, say: impl Into<String>) -> Ui {
        self.actions.push(Button {
            label: label.into(),
            say: say.into(),
        });
        self
    }

    /// The same answer as text: title, then each card on a line or two, then what can be said.
    pub fn text(&self) -> String {
        let mut out = vec![self.title.clone()];
        if !self.subtitle.is_empty() {
            out[0] = format!("{} ({})", self.title, self.subtitle);
        }
        for c in &self.cards {
            let mut head = format!("- {}", c.title);
            if !c.badge.is_empty() {
                head.push_str(&format!(" [{}]", c.badge));
            }
            if !c.subtitle.is_empty() {
                head.push_str(&format!(": {}", c.subtitle));
            }
            if !c.source.is_empty() {
                head.push_str(&format!(" (from {})", c.source));
            }
            out.push(head);
            for s in &c.steps {
                let mut l = format!("    [{}] {}", if s.state.is_empty() { "step" } else { &s.state }, s.label);
                if !s.detail.is_empty() {
                    l.push_str(&format!(" - {}", s.detail));
                }
                out.push(l);
            }
            if let Some(t) = &c.table {
                out.push(format!("    {}", t.columns.join(" | ")));
                for r in &t.rows {
                    out.push(format!("    {}", r.join(" | ")));
                }
            }
            for i in &c.items {
                let mut l = format!("    {}", i.title);
                if !i.subtitle.is_empty() {
                    l.push_str(&format!(" ({})", i.subtitle));
                }
                if !i.value.is_empty() {
                    l.push_str(&format!(": {}", i.value));
                }
                if !i.say.is_empty() {
                    l.push_str(&format!(" -> say \"{}\"", i.say));
                }
                out.push(l);
            }
            for ch in &c.compare {
                let mut l = format!("    option {}", ch.title);
                if !ch.value.is_empty() {
                    l.push_str(&format!(": {}", ch.value));
                }
                if ch.best {
                    l.push_str(" (best)");
                }
                out.push(l);
                for x in &ch.lines {
                    out.push(format!("      {x}"));
                }
            }
            if let Some(m) = &c.metric {
                let mut l = format!("    {}", m.value);
                if !m.label.is_empty() {
                    l.push_str(&format!(" {}", m.label));
                }
                if !m.delta.is_empty() {
                    l.push_str(&format!(" ({})", m.delta));
                }
                out.push(l);
            }
            if let Some(ch) = &c.chart {
                let pts: Vec<String> = ch
                    .labels
                    .iter()
                    .zip(&ch.values)
                    .map(|(l, v)| format!("{l} {v}{}", ch.unit))
                    .collect();
                out.push(format!("    {}", pts.join(", ")));
            }
            for l in &c.lines {
                out.push(format!("    {l}"));
            }
            for b in &c.actions {
                out.push(format!(
                    "    say \"{}\" to {}",
                    b.say,
                    b.label.to_lowercase()
                ));
            }
        }
        for b in &self.actions {
            out.push(format!("say \"{}\" to {}", b.say, b.label.to_lowercase()));
        }
        out.join("\n")
    }

    /// The reply a tool returns: the document and its text.
    pub fn to_reply(&self) -> String {
        serde_json::json!({"ui": self, "text": self.text()}).to_string()
    }

    /// A tool reply back into a document, if it is one.
    pub fn from_reply(s: &str) -> Option<(Ui, String)> {
        let v: serde_json::Value = serde_json::from_str(s).ok()?;
        let ui: Ui = serde_json::from_value(v.get("ui")?.clone()).ok()?;
        Some((ui, v["text"].as_str().unwrap_or_default().to_string()))
    }
}

impl Card {
    pub fn new(title: impl Into<String>) -> Card {
        Card {
            title: title.into(),
            ..Default::default()
        }
    }
    pub fn subtitle(mut self, s: impl Into<String>) -> Card {
        self.subtitle = s.into();
        self
    }
    pub fn line(mut self, l: impl Into<String>) -> Card {
        self.lines.push(l.into());
        self
    }
    pub fn badge(mut self, b: impl Into<String>) -> Card {
        self.badge = b.into();
        self
    }
    pub fn tone(mut self, t: &str) -> Card {
        self.tone = t.into();
        self
    }
    pub fn metric(
        mut self,
        value: impl Into<String>,
        label: impl Into<String>,
        delta: impl Into<String>,
    ) -> Card {
        self.metric = Some(Metric {
            value: value.into(),
            label: label.into(),
            delta: delta.into(),
        });
        self
    }
    pub fn chart(mut self, kind: &str, labels: Vec<String>, values: Vec<f64>, unit: &str) -> Card {
        self.chart = Some(Chart {
            kind: kind.to_string(),
            labels,
            values,
            unit: unit.to_string(),
        });
        self
    }
    pub fn progress(mut self, p: f32) -> Card {
        self.progress = Some(p.clamp(0.0, 1.0));
        self
    }
    pub fn image(mut self, path: impl Into<String>) -> Card {
        self.image = path.into();
        self
    }
    pub fn button(mut self, label: impl Into<String>, say: impl Into<String>) -> Card {
        self.actions.push(Button {
            label: label.into(),
            say: say.into(),
        });
        self
    }
    pub fn step(mut self, label: impl Into<String>, detail: impl Into<String>, state: &str) -> Card {
        self.steps.push(Step {
            label: label.into(),
            detail: detail.into(),
            state: state.to_string(),
        });
        self
    }
    pub fn table(mut self, columns: Vec<String>, rows: Vec<Vec<String>>) -> Card {
        self.table = Some(Table { columns, rows });
        self
    }
    pub fn item(
        mut self,
        title: impl Into<String>,
        subtitle: impl Into<String>,
        value: impl Into<String>,
        icon: impl Into<String>,
        say: impl Into<String>,
    ) -> Card {
        self.items.push(Item {
            title: title.into(),
            subtitle: subtitle.into(),
            value: value.into(),
            icon: icon.into(),
            say: say.into(),
        });
        self
    }
    pub fn option(mut self, title: impl Into<String>, lines: Vec<String>, value: impl Into<String>, best: bool) -> Card {
        self.compare.push(Choice {
            title: title.into(),
            lines,
            value: value.into(),
            best,
        });
        self
    }
    pub fn source(mut self, s: impl Into<String>) -> Card {
        self.source = s.into();
        self
    }
}

#[cfg(test)]
mod d3_tests {
    use super::*;

    fn rich() -> Ui {
        Ui::new("Trip")
            .kind("steps")
            .layout("steps")
            .accent("sky")
            .card(
                Card::new("Plan")
                    .source("Connector")
                    .step("Find flights", "3 found", "done")
                    .step("Share with Ravi", "waits for your PIN", "wait")
                    .table(
                        vec!["Flight".into(), "Price".into()],
                        vec![vec!["6E-204".into(), "₹4,120".into()], vec!["AI-505".into(), "₹3,980".into()]],
                    )
                    .item("Hotel Lotus", "2 km", "₹2,400", "bed", "book hotel lotus")
                    .option("Train", vec!["8 h".into()], "₹900", false)
                    .option("Flight", vec!["1 h".into()], "₹3,980", true),
            )
    }

    #[test]
    fn the_new_pieces_survive_a_round_trip() {
        let ui = rich();
        let text = ui.to_reply();
        let (back, _) = Ui::from_reply(&text).unwrap();
        assert_eq!(back, ui);
        assert_eq!(back.layout, "steps");
        assert_eq!(back.accent, "sky");
        assert!(back.cards[0].steps[1].state == "wait");
        assert!(back.cards[0].compare[1].best);
    }

    #[test]
    fn the_text_form_names_every_step_cell_and_item() {
        let t = rich().text();
        for s in ["Find flights", "Share with Ravi", "waits for your PIN", "6E-204", "₹3,980", "Hotel Lotus", "(from Connector)", "option Flight", "(best)"] {
            assert!(t.contains(s), "missing {s} in:\n{t}");
        }
    }

    #[test]
    fn an_old_document_without_the_new_fields_still_reads() {
        let old = r#"{"ui":{"title":"Weather","cards":[{"title":"Now"}]},"text":"Weather"}"#;
        let (ui, _) = Ui::from_reply(old).unwrap();
        assert!(ui.layout.is_empty() && ui.accent.is_empty());
        assert!(ui.cards[0].steps.is_empty() && ui.cards[0].table.is_none());
    }
}
